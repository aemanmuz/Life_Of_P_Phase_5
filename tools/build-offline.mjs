/**
 * Create a classic-script, file:// compatible bundle from the Phase 5 ES modules.
 * This minimal builder supports the named static imports used by this project.
 * It does not require npm dependencies or a connection to the internet.
 * Keep editing js/*.js; run `npm run build:offline` if you want those changes
 * reflected in the version that opens by double-clicking index.html.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const entry = path.join(root, 'js', 'main.js');
const visited = new Set();
const ordered = [];
const importLine = /^\s*import\s+\{[^}]+\}\s+from\s+['"]([^'"]+)['"];?\s*$/gm;

function visit(file) {
  file = path.resolve(file);
  if (visited.has(file)) return;
  const source = fs.readFileSync(file, 'utf8');
  for (const [, spec] of source.matchAll(importLine)) {
    if (!spec.startsWith('.')) throw new Error(`Only relative imports supported: ${spec}`);
    visit(path.resolve(path.dirname(file), spec));
  }
  visited.add(file);
  ordered.push({ file, source });
}
visit(entry);

const source = [
  '/* Life of P - v0.5.0 standalone browser fallback.',
  '   Auto-generated from the modular ES6 source; do not edit this file directly.',
  '   Rebuild it with: npm run build:offline */',
  '(() => {',
  "'use strict';",
  ...ordered.map(({file, source}) => {
    const relative = path.relative(root, file).replaceAll(path.sep, '/');
    return `\n/* --- ${relative} --- */\n${source.replace(importLine, '').replace(/\bexport\s+(?=(?:const|let|var|class|function)\b)/g, '')}`;
  }),
  '})();',
  ''
].join('\n');

const out = path.join(root, 'js', 'offline.bundle.js');
fs.writeFileSync(out, source, 'utf8');
console.log(`Created js/offline.bundle.js from ${ordered.length} modules (${source.length} characters)`);
